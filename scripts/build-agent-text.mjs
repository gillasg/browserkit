import { existsSync } from "node:fs";
import { readFile, readdir, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { format } from "prettier";

// One source for the agent-facing text. browserkit/docs/agent/sections holds the common Markdown;
// this writes browserkit's skill, Aeon's skill (same sections, browserkit→aeon, plus Aeon-only
// parts) and Aeon's shared browser-code guidance. Run with --check in CI to fail on stale output.

const repo = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const aeonRepo = resolve(repo, "..", "aeon-browser");
const check = process.argv.includes("--check");
const MARKDOWN_HEADER =
  "<!-- Generated by browserkit/scripts/build-agent-text.mjs from browserkit/docs/agent/sections. Do not edit; edit the sources and run pnpm agent-text. -->";
const TS_HEADER =
  "// Generated by browserkit/scripts/build-agent-text.mjs from browserkit/docs/agent/guidance.md and Aeon's guidance-extra.md. Do not edit.";

const outputs = [];
const sections = await readSections(join(repo, "docs", "agent", "sections"));
const browserkitFront = await read(join(repo, "docs", "agent", "frontmatter-browserkit.md"));
const browserkitSkill = assemble([
  browserkitFront,
  MARKDOWN_HEADER,
  sections.get("00-intro"),
  sections.get("01-setup"),
  ...commonSections(sections),
]).replaceAll("{{workspace}}", browserkitWorkspace());
assertNoAeon(browserkitSkill);
outputs.push({ path: join(repo, "skills", "browserkit", "SKILL.md"), content: browserkitSkill });

if (existsSync(join(aeonRepo, "skills", "aeon"))) {
  const parts = await readSections(join(aeonRepo, "skills", "aeon", "parts"));
  const aeonSkill = assemble([
    parts.get("frontmatter"),
    MARKDOWN_HEADER,
    parts.get("00-intro"),
    rewriteForAeon(sections.get("01-setup")),
    parts.get("10-handoff"),
    ...commonSections(sections).map(rewriteForAeon),
    parts.get("30-recipes"),
    parts.get("20-routines"),
    parts.get("40-review"),
  ]);
  outputs.push({ path: join(aeonRepo, "skills", "aeon", "SKILL.md"), content: aeonSkill });
}

// browserkit's own browser_code tool description: its primer plus the same shared guidance.
{
  const primer = (await read(join(repo, "docs", "agent", "primer-browserkit.md"))).trim();
  const shared = split(await read(join(repo, "docs", "agent", "guidance.md")));
  const descriptionPath = join(repo, "apps", "bridge", "src", "guidance.ts");
  const source = [
    "// Generated by browserkit/scripts/build-agent-text.mjs from browserkit/docs/agent (primer-browserkit.md and guidance.md). Do not edit.",
    "export const browserCodeDescription = [",
    ...[primer, ...shared].map((paragraph) => `  ${JSON.stringify(paragraph)},`),
    '].join("\\n\\n");',
    "",
  ].join("\n");
  outputs.push({
    path: descriptionPath,
    content: await format(source, { filepath: descriptionPath }),
  });
}

if (existsSync(join(aeonRepo, "packages", "pi-adapter"))) {
  const guidance = await guidanceSource();
  const guidancePath = join(aeonRepo, "packages", "pi-adapter", "src", "browser-code-guidance.ts");
  outputs.push({
    path: guidancePath,
    content: await format(guidance, { filepath: guidancePath }),
  });
}

let stale = 0;
for (const output of outputs) {
  let current = "";
  try {
    current = await readFile(output.path, "utf8");
  } catch {
    // Missing is stale too.
  }
  if (current === output.content) continue;
  stale += 1;
  if (check) process.stderr.write(`stale: ${output.path}\n`);
  else {
    await writeFile(output.path, output.content);
    process.stdout.write(`wrote ${output.path}\n`);
  }
}
if (check && stale) {
  process.stderr.write("Agent text is stale. Run `pnpm agent-text` in browserkit.\n");
  process.exit(1);
}

async function readSections(folder) {
  const map = new Map();
  for (const file of (await readdir(folder)).filter((name) => name.endsWith(".md")).sort())
    map.set(file.replace(/\.md$/, ""), await read(join(folder, file)));
  return map;
}

function commonSections(sections) {
  return ["02-which-way", "03-browser-code", "04-reading", "05-forms", "06-signin"]
    .map((name) => sections.get(name))
    .concat(
      ["07-blocked", "08-sites", "09-sessions", "10-habits", "11-pack", "12-providers"].map(
        (name) => sections.get(name),
      ),
    );
}

function rewriteForAeon(text) {
  return text
    .replaceAll("{{workspace}}", "`%LOCALAPPDATA%\\Aeon\\data\\external\\<session>` on Windows")
    .replaceAll("browserkit", "aeon")
    .replaceAll("aeon's", "Aeon's");
}

function browserkitWorkspace() {
  return "`%LOCALAPPDATA%\\browserkit\\workspaces\\<session>` on Windows, `~/.local/share/browserkit/...` elsewhere";
}

function assemble(parts) {
  const text = parts
    .filter((part) => part !== undefined)
    .map((part) => part.trim())
    .filter(Boolean)
    .join("\n\n");
  return text + "\n";
}

async function read(path) {
  return readFile(path, "utf8");
}

function assertNoAeon(text) {
  if (/\baeon\b/i.test(text))
    throw new Error("browserkit's generated skill mentions Aeon; fix docs/agent/sections");
}

async function guidanceSource() {
  const shared = split(await read(join(repo, "docs", "agent", "guidance.md")));
  const extra = split(await read(join(aeonRepo, "packages", "pi-adapter", "guidance-extra.md")));
  const paragraphs = [...shared];
  paragraphs[0] = `${paragraphs[0]}\n${extra[0] ?? ""}`.trim();
  const primer = extra[1] ?? "";
  return [
    TS_HEADER,
    `export const browserRuntimePrimer = ${JSON.stringify(primer)};`,
    "",
    "export const browserCodeGuidelines = [",
    ...paragraphs.map((paragraph) => `  ${JSON.stringify(paragraph)},`),
    "];",
    "",
  ].join("\n");
}

function split(text) {
  return text
    .split(/^\s*---\s*$/m)
    .map((part) => part.trim())
    .filter(Boolean);
}
